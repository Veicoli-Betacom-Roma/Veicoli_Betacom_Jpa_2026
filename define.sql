
    create table alimentazione (
        id integer generated by default as identity,
        tipo_alimentazione varchar(25) not null,
        primary key (id)
    );

    create table bici (
        id integer not null,
        numero_marce integer not null,
        pieghevole boolean not null,
        primary key (id)
    );

    create table categoria (
        id integer generated by default as identity,
        nome_categoria varchar(30) not null,
        primary key (id)
    );

    create table colore (
        id integer generated by default as identity,
        nome_colore varchar(30) not null,
        primary key (id)
    );

    create table macchina (
        cilindrata integer not null,
        id integer not null,
        numero_porte integer not null,
        targa varchar(15) not null unique,
        primary key (id)
    );

    create table moto (
        cilindrata integer not null,
        id integer not null,
        targa varchar(15) not null unique,
        primary key (id)
    );

    create table veicoli (
        alimentazione_id integer,
        anno_produzione date not null,
        categoria_id integer,
        colore_id integer,
        id integer generated by default as identity,
        numero_ruote integer not null,
        marca varchar(50) not null,
        modello varchar(100) not null,
        primary key (id)
    );

